// This is the LCD decoder module for a single char

module decodeCharLCD (input logic[7:0] char,
                    output logic[7:0] b);

    // char is the associated ASCII value
    // link to ASCII table: https://learn.sparkfun.com/tutorials/ascii/all?print=1   

    always_comb begin
        case(char):
            0'h20: b = 0011_0000; // space
            0'h30: b = 0011_0000; // 0
            0'h40: b = 0100_0000; // @
            0'h50: b = 0101_0000; // P
            0'h60: b = 0110_0000; // `
            0'h70: b = 0111_0000; // p

            0'h21: b = 0010_0001; // !
            0'h31: b = 0011_0001; // 1
            0'h41: b = 0100_0001; // A
            0'h51: b = 0101_0001; // Q
            0'h61: b = 0110_0001; // a
            0'h71: b = 0111_0001; // q

            0'h22: b = 0010_0010; // "
            0'h32: b = 0011_0010; // 2
            0'h42: b = 0100_0010; // B
            0'h52: b = 0101_0010; // R
            0'h62: b = 0110_0010; // b
            0'h72: b = 0111_0010; // r

            0'h23: b = 0010_0011; // #
            0'h33: b = 0011_0011; // 3
            0'h43: b = 0100_0011; // C
            0'h53: b = 0101_0011; // S
            0'h63: b = 0110_0011; // c
            0'h73: b = 0111_0011; // s

            0'h24: b = 0010_0100; // $
            0'h34: b = 0011_0100; // 4
            0'h44: b = 0100_0100; // D
            0'h54: b = 0101_0100; // T
            0'h64: b = 0110_0100; // d
            0'h74: b = 0111_0100; // t

            0'h25: b = 0010_0101; // %
            0'h35: b = 0011_0101; // 5
            0'h45: b = 0100_0101; // E
            0'h55: b = 0101_0101; // U
            0'h65: b = 0110_0101; // e
            0'h75: b = 0111_0101; // u

            0'h26: b = 0010_0110; // &
            0'h36: b = 0011_0110; // 6
            0'h46: b = 0100_0110; // F
            0'h56: b = 0101_0110; // V
            0'h66: b = 0110_0110; // f
            0'h76: b = 0111_0110; // v

            0'h27: b = 0010_0111; // '
            0'h37: b = 0011_0111; // 7
            0'h47: b = 0100_0111; // G
            0'h57: b = 0101_0111; // W
            0'h67: b = 0110_0111; // g
            0'h77: b = 0111_0111; // w

            0'h28: b = 0010_1000; // (
            0'h38: b = 0011_1000; // 8
            0'h48: b = 0100_1000; // H
            0'h58: b = 0101_1000; // X
            0'h68: b = 0110_1000; // h
            0'h78: b = 0111_1000; // x

            0'h29: b = 0010_1001; // )
            0'h39: b = 0011_1001; // 9
            0'h49: b = 0100_1001; // I
            0'h59: b = 0101_1001; // Y
            0'h69: b = 0110_1001; // i
            0'h79: b = 0111_1001; // y

            0'h2A: b = 0010_1010; // *
            0'h3A: b = 0011_1010; // :
            0'h4A: b = 0100_1010; // J
            0'h5A: b = 0101_1010; // Z
            0'h6A: b = 0110_1010; // j
            0'h7A: b = 0111_1010; // z

            0'h2B: b = 0010_1011; // +
            0'h3B: b = 0011_1011; // ;
            0'h4B: b = 0100_1011; // K
            0'h5B: b = 0101_1011; // [
            0'h6B: b = 0110_1011; // k
            0'h7B: b = 0111_1011; // {

            0'h2C: b = 0010_1100; // ,
            0'h3C: b = 0011_1100; // <
            0'h4C: b = 0100_1100; // L
            0'h5C: b = 0101_1100; // come back later
            0'h6C: b = 0110_1100; // l
            0'h7C: b = 0111_1100; // |

            0'h2D: b = 0010_1101; // -
            0'h3D: b = 0011_1101; // =
            0'h4D: b = 0100_1101; // M
            0'h5D: b = 0101_1101; // ]
            0'h6D: b = 0110_1101; // m
            0'h7D: b = 0111_1101; // }

            0'h2E: b = 0010_1110; // -
            0'h3E: b = 0011_1110; // >
            0'h4E: b = 0100_1110; // N
            0'h5E: b = 0101_1110; // ^
            0'h6E: b = 0110_1110; // n
            // ->: b = 0111_1110; // ->

            0'h2F: b = 0010_1111; // /
            0'h3F: b = 0011_1111; // ?
            0'h4F: b = 0100_1111; // O
            0'h5F: b = 0101_1111; // _
            0'h6F: b = 0110_1111; // o
            // <-: b = 0111_1111; // <-

        endcase
    end

endmodule